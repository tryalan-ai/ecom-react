"""RSS 2.0 feed generation.

The feed lists every published page (the index excepted) using the page's
front-matter ``date`` when present and the build date otherwise. Everything is
rendered with the standard library's XML escaping helpers, so page titles and
excerpts are safe inside the document.
"""

from __future__ import annotations

from datetime import date, datetime, timezone
from email.utils import format_datetime
from xml.sax.saxutils import escape as xml_escape

# Date formats accepted in front matter, tried in order.
_DATE_FORMATS = (
    "%Y-%m-%d",
    "%Y-%m-%dT%H:%M:%S",
    "%Y/%m/%d",
    "%d %B %Y",
    "%B %d, %Y",
)


def parse_date(value):
    """Coerce a front-matter value into an aware :class:`datetime`, or None."""
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    if isinstance(value, date):
        return datetime(value.year, value.month, value.day, tzinfo=timezone.utc)
    if isinstance(value, str):
        text = value.strip()
        for fmt in _DATE_FORMATS:
            try:
                return datetime.strptime(text, fmt).replace(tzinfo=timezone.utc)
            except ValueError:
                continue
    return None


def item_datetime(page, default):
    """The publication date for *page*: its front-matter date or *default*."""
    return parse_date(page.metadata.get("date")) or default


def rfc822(value):
    """Format a datetime as an RFC 822 date, which RSS 2.0 requires."""
    if not isinstance(value, datetime):
        value = datetime.now(timezone.utc)
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    return format_datetime(value)


def join_url(base_url, path):
    """Join a site base URL and a relative path into an absolute URL."""
    if not base_url:
        return path
    return base_url.rstrip("/") + "/" + path.lstrip("/")


def feed_pages(pages):
    """Pages that belong in the feed: everything except the index."""
    return [
        page
        for page in pages
        if page.url != "index.html" and page.metadata.get("feed") is not False
    ]


def render_rss(
    pages,
    site_title,
    base_url="",
    build_date=None,
    description=None,
    items=None,
):
    """Render an RSS 2.0 document as a string."""
    build_date = build_date or datetime.now(timezone.utc)
    if description is None:
        description = "%s - a static site generated by sitegen." % site_title
    if items is None:
        items = feed_pages(pages)

    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<rss version="2.0">',
        "<channel>",
        "<title>%s</title>" % xml_escape(str(site_title)),
        "<link>%s</link>" % xml_escape(join_url(base_url, "index.html")),
        "<description>%s</description>" % xml_escape(description),
        "<language>en</language>",
        "<lastBuildDate>%s</lastBuildDate>" % rfc822(build_date),
        "<generator>sitegen</generator>",
    ]
    for page in items:
        link = join_url(base_url, page.url)
        published = item_datetime(page, build_date)
        lines.append("<item>")
        lines.append("<title>%s</title>" % xml_escape(str(page.title)))
        lines.append("<link>%s</link>" % xml_escape(link))
        lines.append('<guid isPermaLink="true">%s</guid>' % xml_escape(link))
        lines.append("<pubDate>%s</pubDate>" % rfc822(published))
        summary = page.excerpt or ""
        if summary:
            lines.append("<description>%s</description>" % xml_escape(summary))
        lines.append("</item>")
    lines.extend(["</channel>", "</rss>"])
    return "\n".join(lines) + "\n"
