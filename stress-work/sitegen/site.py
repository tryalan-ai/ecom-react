"""Assemble a folder of Markdown files into a static HTML site.

The builder walks a source directory, loads every Markdown file as a
:class:`Page`, renders each one through a template with a shared navigation
block, and writes an ``index.html`` listing all pages.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path

from .blocks import collect_headings, extract_title, parse_blocks, render_blocks
from .frontmatter import parse_front_matter, split_list
from .htmlutil import escape_attr, escape_text, rel_url
from .inline import strip_markdown
from .template import render_template

MARKDOWN_SUFFIXES = (".md", ".markdown")

DEFAULT_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{{ page.title }} &middot; {{ site.title }}</title>
<link rel="stylesheet" href="{{ page.asset_prefix }}style.css">
</head>
<body>
<header class="site-header">
<a class="site-title" href="{{ page.home }}">{{ site.title }}</a>
</header>
<nav class="site-nav">
{{{ nav }}}
</nav>
<main class="content">
{{{ content }}}
</main>
<footer class="site-footer">Generated by sitegen</footer>
</body>
</html>
"""


class SiteError(Exception):
    """Raised when the site cannot be built."""


@dataclass
class Page:
    """A single Markdown source file and its rendered form."""

    source: str
    rel: str
    url: str
    title: str
    metadata: dict = field(default_factory=dict)
    blocks: list = field(default_factory=list)
    body_html: str = ""
    headings: list = field(default_factory=list)
    tags: list = field(default_factory=list)


@dataclass
class BuildResult:
    """What :func:`build_site` produced, useful for callers and tests."""

    output_dir: str
    pages: list
    written: list
    index_path: str


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------
def page_url(rel_path):
    """Map a relative source path to its output URL (``.md`` -> ``.html``)."""
    lower = rel_path.lower()
    for suffix in MARKDOWN_SUFFIXES:
        if lower.endswith(suffix):
            return rel_path[: -len(suffix)] + ".html"
    return rel_path + ".html"


def discover_sources(source_dir):
    """Return every Markdown file under *source_dir*, sorted by relative path."""
    root = Path(source_dir)
    if not root.is_dir():
        raise SiteError("source directory does not exist: %s" % source_dir)
    found = []
    for path in root.rglob("*"):
        if path.is_file() and path.suffix.lower() in MARKDOWN_SUFFIXES:
            found.append(path)
    found.sort(key=lambda p: p.relative_to(root).as_posix())
    return found


def _title_from_path(rel_path):
    stem = rel_path.rsplit("/", 1)[-1]
    for suffix in MARKDOWN_SUFFIXES:
        if stem.lower().endswith(suffix):
            stem = stem[: -len(suffix)]
            break
    return stem.replace("-", " ").replace("_", " ").strip().title()


def load_page(path, root):
    """Read and parse a single Markdown file into a :class:`Page`."""
    text = Path(path).read_text(encoding="utf-8")
    metadata, body = parse_front_matter(text)
    blocks = parse_blocks(body)
    rel = Path(os.path.relpath(str(path), str(root))).as_posix()

    raw_title = metadata.get("title")
    title = str(raw_title).strip() if raw_title else (extract_title(blocks) or _title_from_path(rel))

    return Page(
        source=str(path),
        rel=rel,
        url=page_url(rel),
        title=title,
        metadata=metadata,
        blocks=blocks,
        body_html=render_blocks(blocks),
        headings=collect_headings(blocks),
        tags=split_list(metadata.get("tags")),
    )


def sort_pages(pages):
    """Order pages for navigation: by ``weight`` then by source path."""

    def key(page):
        weight = page.metadata.get("weight")
        return (weight if isinstance(weight, int) else 10**6, page.rel)

    return sorted(pages, key=key)


# ---------------------------------------------------------------------------
# Rendering helpers
# ---------------------------------------------------------------------------
def excerpt(blocks, limit=160):
    """Plain-text summary taken from the first paragraph of a page."""
    for node in blocks:
        if node["type"] == "paragraph":
            text = strip_markdown(node["text"]).replace("\n", " ")
            text = " ".join(text.split())
            if len(text) > limit:
                text = text[: limit - 1].rstrip() + "\u2026"
            return text
    return ""


def build_nav(pages, current_url, include_home=True):
    """Render the ``<nav>`` list, linking each page relative to *current_url*."""
    entries = []
    has_index_page = any(page.url == "index.html" for page in pages)
    if include_home and not has_index_page:
        entries.append(("Home", "index.html"))
    for page in pages:
        entries.append((page.title, page.url))

    items = []
    for title, url in entries:
        href = rel_url(url, current_url)
        active = ' class="active"' if url == current_url else ""
        items.append('<li%s><a href="%s">%s</a></li>' % (active, escape_attr(href), escape_text(title)))
    return "<ul>\n" + "\n".join(items) + "\n</ul>"


def render_toc(headings):
    """Render a table of contents from a page's headings (levels 2-3)."""
    items = [h for h in headings if h["level"] in (2, 3)]
    if not items:
        return ""
    parts = ["<ul class=\"toc\">"]
    for heading in items:
        parts.append(
            '<li class="level-%d"><a href="#%s">%s</a></li>'
            % (heading["level"], escape_attr(heading["id"]), escape_text(strip_markdown(heading["text"])))
        )
    parts.append("</ul>")
    return "\n".join(parts)


def render_index_body(pages, current_url="index.html", site_title=None):
    """Build the HTML body for the auto-generated index page."""
    parts = []
    if site_title:
        parts.append("<h1>%s</h1>" % escape_text(site_title))
    parts.append('<ul class="page-list">')
    for page in pages:
        href = rel_url(page.url, current_url)
        summary = excerpt(page.blocks)
        entry = '<li><a href="%s">%s</a>' % (escape_attr(href), escape_text(page.title))
        if summary:
            entry += '<p class="excerpt">%s</p>' % escape_text(summary)
        if page.tags:
            entry += '<span class="tags">%s</span>' % escape_text(", ".join(page.tags))
        entry += "</li>"
        parts.append(entry)
    parts.append("</ul>")
    return "\n".join(parts)


def _page_context(page, pages, site_title):
    return {
        "site": {
            "title": site_title,
            "pages": [{"title": p.title, "url": p.url} for p in pages],
        },
        "page": {
            "title": page.title,
            "url": page.url,
            "rel": page.rel,
            "tags": page.tags,
            "headings": page.headings,
            "home": rel_url("index.html", page.url),
            "asset_prefix": _asset_prefix(page.url),
        },
        "content": page.body_html,
        "nav": build_nav(pages, page.url),
        "toc": render_toc(page.headings),
    }


def _asset_prefix(url):
    """Relative prefix pointing at the site root from *url*'s directory."""
    home = rel_url("index.html", url)
    if home == "index.html":
        return ""
    return home[: -len("index.html")]


# ---------------------------------------------------------------------------
# Building
# ---------------------------------------------------------------------------
def _load_template(template_path):
    if template_path is None:
        return DEFAULT_TEMPLATE
    path = Path(template_path)
    if not path.is_file():
        raise SiteError("template does not exist: %s" % template_path)
    return path.read_text(encoding="utf-8")


def build_site(
    source_dir,
    output_dir,
    template_path=None,
    site_title="sitegen",
    include_drafts=False,
):
    """Build the whole site and return a :class:`BuildResult`."""
    root = Path(source_dir)
    if not root.is_dir():
        raise SiteError("source directory does not exist: %s" % source_dir)

    template = _load_template(template_path)

    pages = [load_page(path, root) for path in discover_sources(root)]
    if not include_drafts:
        pages = [page for page in pages if page.metadata.get("draft") is not True]
    pages = sort_pages(pages)

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    written = []
    for page in pages:
        html = render_template(template, _page_context(page, pages, site_title))
        destination = out / page.url
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(html, encoding="utf-8")
        written.append(str(destination))

    index_path = out / "index.html"
    has_explicit_index = any(page.url == "index.html" for page in pages)
    if not has_explicit_index:
        context = {
            "site": {
                "title": site_title,
                "pages": [{"title": p.title, "url": p.url} for p in pages],
            },
            "page": {
                "title": site_title,
                "url": "index.html",
                "rel": "index.md",
                "tags": [],
                "headings": [],
                "home": "index.html",
                "asset_prefix": "",
            },
            "content": render_index_body(pages, "index.html", site_title),
            "nav": build_nav(pages, "index.html"),
            "toc": "",
        }
        index_path.write_text(render_template(template, context), encoding="utf-8")
        written.append(str(index_path))

    return BuildResult(
        output_dir=str(out),
        pages=pages,
        written=written,
        index_path=str(index_path),
    )
