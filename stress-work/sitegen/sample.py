"""Generate a synthetic sample site (default: 300 Markdown pages).

The generator is deterministic: the same ``seed`` always produces byte-for-byte
identical files, which makes it safe to use in tests and benchmarks.
"""

import os
import random
from datetime import date, timedelta

__all__ = ["generate_sample_site", "DEFAULT_COUNT", "SAMPLE_SECTIONS"]

DEFAULT_COUNT = 300
SAMPLE_SECTIONS = ["guides", "reference", "tutorials", "blog", "api"]

_TOPICS = [
    "Getting started",
    "Configuration",
    "Routing",
    "Authentication",
    "Caching",
    "Deployment",
    "Testing",
    "Troubleshooting",
    "Performance",
    "Migration",
    "Security",
    "Internals",
]

_SENTENCES = [
    "This page explains the core ideas in plain language.",
    "Read the linked material before continuing.",
    "The examples below are runnable as-is.",
    "Keep the defaults unless you have a reason to change them.",
    "Everything here is covered by the automated test suite.",
    "Prefer the standard library when it is good enough.",
]

_CODE_SNIPPETS = [
    "def add(a, b):\n    return a + b",
    "for item in items:\n    print(item)",
    "value = data.get('key', 'default')",
    "with open(path) as handle:\n    text = handle.read()",
]


def generate_sample_site(target_dir, count=DEFAULT_COUNT, seed=1337):
    """Write ``count`` Markdown files into ``target_dir``.

    Returns the list of relative paths that were created (sorted). The first
    page is always ``index.md``.
    """
    rng = random.Random(seed)
    os.makedirs(target_dir, exist_ok=True)
    created = []
    start = date(2024, 1, 1)

    for i in range(count):
        if i == 0:
            rel = "index.md"
            title = "Sample Site"
            section = "home"
            description = "Home page for the generated sample site."
            order = 0
        else:
            section = SAMPLE_SECTIONS[(i - 1) % len(SAMPLE_SECTIONS)]
            rel = "%s/page-%03d.md" % (section, i)
            topic = _TOPICS[(i - 1) % len(_TOPICS)]
            title = "%s: %s" % (topic, i)
            description = "Synthetic %s page number %d." % (section, i)
            order = i

        pub = start + timedelta(days=i)
        body = _render_body(rng, title, section, i)
        text = _front_matter(title, description, order, pub) + body
        full = os.path.join(target_dir, rel)
        os.makedirs(os.path.dirname(full) or ".", exist_ok=True)
        with open(full, "w", encoding="utf-8") as handle:
            handle.write(text)
        created.append(rel)

    return sorted(created)


def _front_matter(title, description, order, pub):
    return (
        "---\n"
        "title: %s\n"
        "description: %s\n"
        "order: %d\n"
        "date: %s\n"
        "tags: [sample, docs]\n"
        "---\n\n" % (title, description, order, pub.isoformat())
    )


def _render_body(rng, title, section, i):
    prefix = "" if i == 0 else "../"
    lines = ["# %s\n" % title, ""]
    lines.append("%s %s\n" % (rng.choice(_SENTENCES), rng.choice(_SENTENCES)))
    lines.append("See the [home page](%sindex.md) for an overview.\n" % prefix)
    lines.append("## Highlights\n")
    for bullet in range(1, 4):
        lines.append("- Point %d for %s" % (bullet, section))
    lines.append("")
    lines.append("## Example\n")
    lines.append("```python\n%s\n```\n" % rng.choice(_CODE_SNIPPETS))
    lines.append("![diagram](%simages/%s-%03d.png)\n" % (prefix, section, i))
    lines.append("> Generated by sitegen's sample generator.\n")
    return "\n".join(lines)
